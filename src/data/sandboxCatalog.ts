export function findBuildZoneAt(x: number, z: number): BuildZoneDefinition | null {
  for (let i = 0; i < BUILD_ZONES.length; i++) {
    const zDef = BUILD_ZONES[i];
    if (Math.abs(x - zDef.centerX) <= zDef.halfW && Math.abs(z - zDef.centerZ) <= zDef.halfD) {
      return zDef;
    }
  }
  return null;
}
